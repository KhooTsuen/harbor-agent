export interface ExtBridge {
  /**
   * 把「界面当前打开的会话」报给主进程。
   *
   * 为什么要报：Edge 扩展读到的页面内容由**扩展进程**经命名管道送进主进程
   * （见 electron/core/ext-bridge.cjs），主进程要决定它落进哪条会话 ——
   * 而「现在打开的是哪条」只有渲染层知道。
   *
   * 尽力而为：没报过 / 报的那条已被删时，主进程会**新建一条专用会话**兜底，
   * 页面内容不会丢。
   */
  extActiveSession: (id: string) => Promise<{ ok: boolean }>
}
