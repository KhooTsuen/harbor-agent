import { create } from 'zustand'

/* ══════════════════════════════════════════════════════════════
   运行日志的「有新条目了」信号

   底栏那个运行日志面板（`bottom/ToolLogPanel.tsx`）以前是
   **打开时拉一次 + 手动点刷新**（当时的理由写在注释里：不常驻轮询，
   和「空闲时不轮询」的原则一致）。

   结果就是用户 2026-09-30 报的那件事：面板开着、Agent 在跑，
   流水**一条都不动**，看着像是「列表满了 200 条就不再刷新」
   （其实跟 200 没关系 —— 列表取的就是最新 200 条，只是没人再去取）。

   改成事件驱动：工具跑完就 +1，面板盯着这个数重新拉一次。
   比轮询省，而且工具一停就完全不动（比「跑着才轮询」还准）。
   ══════════════════════════════════════════════════════════════ */

interface AuditSignal {
  /** 每有一条新的运行记录就 +1（面板只看它变没变，不看具体值） */
  version: number
  /** 工具跑完调它（在 `thread/streamEvents.ts` 里，和任务刷新挨着） */
  bump: () => void
}

export const useAuditStore = create<AuditSignal>((set) => ({
  version: 0,
  bump: () => set((s) => ({ version: s.version + 1 })),
}))
