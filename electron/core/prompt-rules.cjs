/**
 * 「做事的规矩」—— 动手前 / 动手时该守的那几条文案（从 `prompt-stack.cjs` 拆出来的）
 *
 * 为什么拆：`prompt-stack.cjs` 是「分层系统提示」的装配（模式 / 权限 / 边界 / 浏览器…），
 * 而那几层是**跟着运行时状态变**的；这里这几条是**跟着用户的做派变**的
 * （先看再改、要不要先给计划、要不要先问、要不要先掂量代价）。加「规模」这一条时
 * 那边只剩 3 行余量（硬约束 #2 是 300），拆的口子就选在这两类的分界上。
 *
 * ⚠️ `prompt-stack.cjs` 会把 `workRules` / `WORK_RULES` 转出去 —— 老引用照旧能用。
 */

/** 「先看再改」—— 和任何开关无关，永远都要说 */
const LOOK_FIRST_RULE = '- **先看再改**。改文件前先 read_file 确认现在的样子，不要凭记忆改。'

/**
 * 「先给计划」这一条 —— `assistant.planFirst` 管的就是它。
 *
 * 关掉它 = 不再要求模型先出计划块：界面上不会有计划栏，完成门禁也不会顶它
 * （门禁只在**有计划且没勾完**时才拦，见 task-steering.cjs）。
 * 这是那个开关**唯一**的落点，所以自检直接钉这段文案在不在（`06-prompt-state`）。
 */
const PLAN_RULE = [
  '- 确实是多步的活（要读好几个文件 / 改好几处 / 跑好几轮），**先给一个 ```plan 块**：',
  '  第一行写任务名（形如 `# 优化启动速度`，一句话说清在做什么），下面每行一条步骤。',
  '  做完一步就把那条标成 `[x]`，再重发一遍**完整**计划（界面照它显示进度）。',
  '  一两句就能答完的事不要写计划块。',
].join('\n')

/**
 * 「开工前先问清楚」这一条 —— `assistant.clarifyFirst` 管的就是它（AG-053）。
 *
 * 为什么值得占提示词的位置：含糊的需求直接开工，最常见的结局是「做完了但不是
 * 用户要的」，而返工比问一句贵得多。这条要说清五件事，少一件都不管用：
 *   ① 什么时候该问（三条触发条件：改法不止一种 / 不好回退 / 范围没说清）—— 不然模型凭感觉；
 *   ② **要问必须调 `ask_user`**（写在正文里不算）—— 2026-10-02 真机逮到过「正文里问」；
 *   ③ 什么时候别问（能自己查出来的、一句话能答完的）—— 不然每轮都先问一遍；
 *   ④ 选项必须带「因为 X 所以 Y」的**具体数字或事实** —— 主观判断帮不了用户决策；
 *   ⑤ 必须有默认选项，且是最保守那个 —— 用户离场时按它继续（见 clarify-timeout.cjs）。
 */
const CLARIFY_RULE = [
  '- **开工前先对齐**：命中下面任意一条，就先调 `ask_user` 把需要用户拿主意的地方摆出来',
  '  （一次最多 3 个问题），**等他答完再动手**：',
  '  · **改法不止一种**：选错了要返工、要重写、要重跑测试；',
  '  · **这一步不好回退**：覆盖 / 删除 / 重写 / 改配置 / 装依赖 / 发布 / 推送；',
  '  · **范围没说清**：只说「处理一下」「整理一下」「优化一下」「看着办」，没说改到什么程度。',
  '  ⚠️ **要问就必须调 `ask_user`**：把问题写在回复正文里不算 —— 正文里的问题界面不会弹卡、',
  '  用户也没法按选项回答，等于没问（2026-10-02 真机验收逮到过这种：读了两步就停下、',
  '  在正文里问「要不要我…」）。上面三条都不命中就直接做，**别问**。',
  '  · 每个选项都要写清「因为 X，所以会有 Y 效果」，X/Y 必须是**具体数字或事实**',
  '    （「多花 30 秒」「新增 3 个文件」「要重跑一遍测试」），不要写「更好」「更稳妥」这类主观判断；',
  '  · 每个问题都要给 `defaultValue`，而且必须是**改动最小、最容易回滚、风险最低**的那个 ——',
  '    用户离场时（超过 10 分钟没键鼠活动）会按它继续，所以选错默认等于替他做了错决定；',
  '  · 用户若说「你看着办」「别问我」「直接做」，就**不要问**，自己拍板，',
  '    并在回复里每个决策留一行「我选了 X，因为 Y」。',
  '- 不该问的别问：能从代码或文件里查出来的、纯风格偏好、一句话就能答完的活，直接做。',
].join('\n')

/**
 * 「动手前把代价说清楚」这一条（A2）—— 规模闸门（`core/tools/scale-gate.cjs`）的提示词那一半。
 *
 * 为什么必须有提示词这一半：闸门只认**代码看得出来**的那几类
 * （递归/批量 + 逃出工作目录、批量外联、盘根）。`npm test` 和「扫描整个项目」在
 * 字符串上长得一样 ——「整个项目多大」只有模型看得出来
 * （用户原话：「代码判断不了，模型可以看」）。
 *
 * 分工：**模型先判断**（该问就问、该说一句就说一句），**闸门兜底**
 * （模型没问就动手 → 拦下、把话还回来）。
 */
const SCALE_RULE = [
  '- **动手前先掂量代价**：这次要花多久、动多少文件、有没有外部影响（下载 / 上传 / 爬站）。',
  '  判据是**规模**，不是「读还是写」—— 只读也可能很贵（扫全盘、递归几十万文件）。',
  '  · **代价大且这轮没说范围** → 先调 `ask_user` 说清「打算做什么、多大范围、大约多久」',
  '    （选项里写具体数字：约几分钟 / 约多少文件 / 影响哪些目录），等他点头再动手；',
  '  · **有界但明显耗时**（在工作目录里装依赖、跑测试、构建、克隆一个仓库）→ **不用问**，',
  '    但动手前用一行说明：在做什么、预计多久；',
  '  · **用户这轮已经说了范围**（「把 C 盘扫一遍」）→ 直接做，别再确认一遍；',
  '  · **小范围只读探测**（看一个目录、读一个文件、查一下版本）→ 直接做；',
  '  · 用户说过「别问我」「你看着办」→ 不许再问，自己拍板并说明理由。',
  '  ⚠️ **别换个写法绕过去**：递归 + 工作目录之外、批量外联、盘根这几类闸门认得出，',
  '  绕过去会被同样拦下，还白花一轮。要问就一次问到位。',
].join('\n')

const REST_RULES = [
  '- 改少量内容用 `edit_file`，别用 `write_file` 整篇覆盖。',
  '- `edit_file` 的 oldText 必须逐字一致（包括缩进）并且在文件里唯一。',
  '- 命令失败时把真实报错读一遍再决定下一步，不要盲目重试。',
  '- 别一次读一大堆文件。先 `list_dir` 看结构，再挑相关的读。',
  '- 回答用简体中文。代码、命令、路径保持原样。',
  '- 不确定的事就说不确定，不要编。',
].join('\n')

/**
 * 做事的规矩。
 *
 * 看着像「提示词礼节」，其实每一条都对应过一次真实损失：
 *   · 不先读就改     → 改错位置
 *   · 用 write_file 覆盖 → 把没看见的内容冲掉
 *   · oldText 不唯一  → 改到第一处而不是该改的那处
 *   · 命令失败就重试  → 把偶发故障刷成必然故障
 *   · 一次读一堆文件 → 上下文被无关内容塞满
 *   · 不掂量代价就动手 → 一条 `dir /s C:\` 跑几分钟、读几十万文件（A2 之前没人管）
 *
 * `planFirst: false` 只去掉「先给计划」那一条，其余照旧。
 * `clarifyFirst: false` 去掉「开工前先对齐」**和**「先掂量代价」两条
 * （AG-053 的开关，也是它的回滚开关）—— 后者要做的事正是调 `ask_user`，
 * 不让问的时候还写着「先问规模」，模型只会来回犹豫。两者共用同一个开关。
 * `clarifyMuted` = 这个对话/任务已经不该再问了（连跳两次、或累计等超上限）：
 * 那时候**规则也不注入**，理由同上。
 */
function workRules(input = {}) {
  /* 两条跟 `ask_user` 走的规矩，共用一个「现在还能不能问他」的判断 */
  const canAsk = input.clarifyFirst !== false && input.clarifyMuted !== true
  return [
    LOOK_FIRST_RULE,
    input.planFirst === false ? '' : PLAN_RULE,
    canAsk ? CLARIFY_RULE : '',
    canAsk ? SCALE_RULE : '',
    REST_RULES,
  ]
    .filter(Boolean)
    .join('\n')
}

/** 默认那一份（= planFirst 开着）—— 自检、文档这些老引用继续能用 */
const WORK_RULES = workRules()

module.exports = {
  LOOK_FIRST_RULE,
  PLAN_RULE,
  CLARIFY_RULE,
  SCALE_RULE,
  REST_RULES,
  workRules,
  WORK_RULES,
}
