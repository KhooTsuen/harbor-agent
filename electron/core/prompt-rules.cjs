/**
 * 做事的规矩。
 *
 * 看着像「提示词礼节」，其实每一条都对应过一次真实损失：
 *   · 不先读就改     → 改错位置
 *   · 用 write_file 覆盖 → 把没看见的内容冲掉
 *   · oldText 不唯一  → 改到第一处而不是该改的那处
 *   · 命令失败就重试  → 把偶发故障刷成必然故障
 *   · 一次读一堆文件 → 上下文被无关内容塞满
 *   · 不掂量代价就动手 → 一条 `dir /s C:\` 跑几分钟、读几十万文件（A2 之前没人管）
 *
 * `planFirst: false` 只去掉「先给计划」那一条，其余照旧。
 * `clarifyFirst: false` 去掉「开工前先对齐」**和**「先掂量代价」两条
 * （AG-053 的开关，也是它的回滚开关）—— 后者要做的事正是调 `ask_user`，
 * 不让问的时候还写着「先问规模」，模型只会来回犹豫。两者共用同一个开关。
 * `clarifyMuted` = 这个对话/任务已经不该再问了（连跳两次、或累计等超上限）：
 * 那时候**规则也不注入**，理由同上。
 * `scaleFirst: false`（A2 的规模层开关）同理去掉「先掂量代价」那一条 ——
 * 闸门都关了还写着「先问规模」，模型只会白问一轮。
 * `TEST_RULE`（改了代码要有验证）**不跟任何开关** —— 它自带边界（末一句把闲聊/只读排除掉），
 * 关掉它等于回到「想到了才跑测试」，而那正是加它的原因。
 * `PLAN_GATE_RULE`（用户说先别动就别自作主张）同样**不跟开关** —— 那是用户当场下的指令。
 *
 * `strictMode`（CE-008 严格模式，默认关）：`true` 才注入 STRICT_RULE（每步强制验证）。
 * 它**不是空承诺**：内核门禁（`task-strict.cjs`）按 task.steps 的结构化事实真拦 ——
 * 每累计 3 次写操作 / 勾计划后未验证 → 顶回；收尾有欠账 → 不许收工。
 * 默认 undefined / false = 不注入，行为与升级前一字不差。
 */
function workRules(input = {}) {
  /* 两条跟 `ask_user` 走的规矩，共用一个「现在还能不能问他」的判断 */
  const canAsk = input.clarifyFirst !== false && input.clarifyMuted !== true
  const wantScale = canAsk && input.scaleFirst !== false
  return [
    LOOK_FIRST_RULE,
    input.planFirst === false ? '' : PLAN_RULE,
    canAsk ? CLARIFY_RULE : '',
    wantScale ? SCALE_RULE : '',
    PLAN_GATE_RULE,
    TEST_RULE,
    /* CE-011：连续失败要换方案（硬判据在 failure-streak.cjs）—— 不跟开关 */
    FAILURE_RULE,
    /* CE-014：内部思考用中文（恒定文本 → 吃缓存命中）—— 不跟开关 */
    CHINESE_THINK_RULE,
    input.strictMode === true ? STRICT_RULE : '',
    REST_RULES,
  ]
    .filter(Boolean)
    .join('\n')
}

/** 默认那一份（= planFirst 开着）—— 自检、文档这些老引用继续能用 */
const WORK_RULES = workRules()

module.exports = {
  LOOK_FIRST_RULE,
  PLAN_RULE,
  CLARIFY_RULE,
  SCALE_RULE,
  TEST_RULE,
  FAILURE_RULE,
  CHINESE_THINK_RULE,
  STRICT_RULE,
  PLAN_GATE_RULE,
  NO_FILLER_RULE,
  REST_RULES,
  BROWSER_GUIDE,
  workRules,
  WORK_RULES,
}
