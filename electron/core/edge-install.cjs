/**
 * 浏览器插件的「一键安装」—— 落盘 / 写注册表 / 报状态，全在主进程。
 *
 * ── 为什么要它 ────────────────────────────────────────────────
 *
 * README 那套手动流程有五步：构建产物 → 在 Edge 里加载 → **抄 32 位扩展 ID** →
 * 跑 install-host.cmd → 回 edge://extensions 重新加载。「抄 ID」最容易错，而且
 * unpacked 扩展的 ID 由**加载路径**推导 —— 目录一挪就失配，症状是「连不上」。
 * 这里做两件事把流程压到两次点击：① manifest 带 `key` → ID 固定，不必再抄；
 * ② 程序自己写宿主清单 + HKCU 注册表（不需要管理员）。
 *
 * ⚠️ **剩下两步没法省**（不是没做，是 Edge 不让）：开发者模式 +「加载解压缩的扩展」
 *   必须人点（Edge 没给扩展「自动加载本地目录」的接口）；静默安装也被微软限死了 ——
 *   「Windows 未加入 AD 域时，强制安装只能装 Edge 加载项商店里列出的扩展」（官方策略
 *   文档原文）。所以这里是引导，不是「装完什么都不用点」。别在界面上写成已安装。
 *
 * ── 安全边界（如实写）──────────────────────────────────────────
 *
 * **渲染层不能指定任何路径。** 源码目录、安装目录、注册表键、wrapper 内容全部在这里
 * 按数据根与程序根算出来；IPC 只收「动作名」。否则等于给界面开了一个「往任意位置写
 * 注册表 + 任意路径当可执行文件」的口子。
 *
 * ── 为什么按 data 根装，而不是装进程序目录 ─────────────────────
 *
 * 便携版程序目录会被整个替换（用户就是这么升级的），扩展产物放进去会被覆盖。放
 * `<data>/edge-ext/sidepanel` 跟着数据走，替换程序不影响。
 *
 * ⚠️ 本模块**不 require electron** —— 自检要能不起 Electron 就真跑一遍（写临时目录）。
 */

const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const { spawnSync } = require('node:child_process')

/** 宿主名（与 extension/lib/native.js 的 HOST 同一个，有自检钉着） */
const HOST_NAME = 'com.harbor.agent'

/** 注册表键：Edge 只认这个位置 */
const REG_KEY = `HKCU\\SOFTWARE\\Microsoft\\Edge\\NativeMessagingHosts\\${HOST_NAME}`

/** 扩展产物相对程序根的位置（打包版与源码树两种布局） */
const SOURCE_PACKAGED = path.join('resources', 'app', 'harbor-edge', 'dist', 'sidepanel')
const SOURCE_DEV = path.join('harbor-edge', 'dist', 'sidepanel')

/**
 * 从 manifest 的 `key`（base64 的 SPKI DER）算扩展 ID。
 *
 * Chromium 的算法：公钥 DER 的 SHA-256，取前 16 字节，每个 hex 数字映射到 a–p。
 * 带 `key` 的 manifest 放哪个目录 ID 都一样 —— 这正是要它解决的问题。
 *
 * @param {string} keyBase64
 * @returns {string} 32 位小写 ID；key 不合法时返回空串
 */
function idFromKey(keyBase64) {
  try {
    const der = Buffer.from(String(keyBase64 ?? ''), 'base64')
    if (der.length < 32) return ''
    const hex = crypto.createHash('sha256').update(der).digest('hex').slice(0, 32)
    return [...hex].map((c) => String.fromCharCode(97 + parseInt(c, 16))).join('')
  } catch {
    return ''
  }
}

/** 扩展产物该从哪读（源码树 vs 打包产物） */
function sourceDir(root) {
  const packaged = path.join(root, SOURCE_PACKAGED)
  if (fs.existsSync(path.join(packaged, 'manifest.json'))) return packaged
  return path.join(root, SOURCE_DEV)
}

/** 扩展产物该装到哪（跟着数据根走，替换程序不影响） */
function targetDir(dataDir) {
  return path.join(String(dataDir ?? ''), 'edge-ext', 'sidepanel')
}

/** 宿主清单（Edge 读的就是它） */
function hostManifestPath(dataDir) {
  return path.join(String(dataDir ?? ''), 'edge-host', `${HOST_NAME}.json`)
}

/** Edge 实际执行的包装器（我们生成，不拷仓库那份 —— 源码树里没有 Harbor.exe） */
function hostWrapperPath(dataDir) {
  return path.join(String(dataDir ?? ''), 'edge-host', 'harbor-host.cmd')
}

/**
 * 生成包装器内容。
 *
 * ★ **必须纯 ASCII**：cmd.exe 按 OEM 代码页（zh-CN 是 GBK）读 .cmd，中文注释会变成
 *   乱码然后被当命令执行 —— 这个坑真踩过（见 install-host.cmd 的头注释）。
 * ★ 不能带 `chcp 65001`：它往 stdout 写字，而 stdout 就是这个 host 的协议通道。
 *
 * @param {{dataDir: string, exe: string, script: string}} p
 */
function wrapperText({ dataDir, exe, script }) {
  const root = String(dataDir ?? '').replace(/\\+$/, '')
  return [
    '@echo off',
    'rem Generated by Harbor (electron/core/edge-install.cjs). Do not edit.',
    'rem This file is the "path" target in the native messaging host manifest.',
    'rem Pure ASCII is mandatory: cmd.exe reads .cmd as the OEM codepage.',
    'setlocal',
    'set ELECTRON_RUN_AS_NODE=1',
    `set HARBOR_DATA_ROOT=${root}\\`,
    `"${exe}" "${script}"`,
    '',
  ].join('\r\n')
}

/**
 * 这台机器上 Harbor 用哪个可执行文件跑 native-host.cjs。
 *
 * 打包版：`<程序根>\Harbor.exe` + `<...>\resources\app\electron\native-host.cjs`
 * 源码树：`<仓库>\node_modules\electron\dist\electron.exe` + `<仓库>\electron\native-host.cjs`
 *
 * @param {string} root 程序根（打包版 = exe 同级；源码树 = 仓库根）
 */
function hostRuntime(root) {
  const exe = path.join(root, 'Harbor.exe')
  const script = path.join(root, 'resources', 'app', 'electron', 'native-host.cjs')
  if (fs.existsSync(exe) && fs.existsSync(script)) return { exe, script, kind: 'packaged' }
  return {
    exe: path.join(root, 'node_modules', 'electron', 'dist', 'electron.exe'),
    script: path.join(root, 'electron', 'native-host.cjs'),
    kind: 'dev',
  }
}

/** 读某个目录下 manifest 里的 key 与 version（读不到返回 null） */
function readManifest(dir) {
  try {
    const json = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'))
    return { key: String(json.key ?? ''), version: String(json.version ?? '') }
  } catch {
    return null
  }
}

/** 读注册表当前指向哪份清单（读不到返回空串） */
function readRegistryPath() {
  const res = spawnSync('reg', ['query', REG_KEY, '/ve'], { encoding: 'utf8', windowsHide: true })
  if (res.status !== 0 || !res.stdout) return ''
  const line = res.stdout.split(/\r?\n/).find((l) => /REG_SZ/i.test(l))
  return line ? line.slice(line.search(/REG_SZ/i) + 'REG_SZ'.length).trim() : ''
}

/** 拷产物到目标目录（内容没变就跳过 —— 6.7 MB 每次都拷没必要） */
function syncTarget(src, dst) {
  const from = readManifest(src)
  const to = readManifest(dst)
  if (from && to && from.key === to.key && from.version === to.version) return { copied: false }
  fs.rmSync(dst, { recursive: true, force: true })
  fs.mkdirSync(path.dirname(dst), { recursive: true })
  fs.cpSync(src, dst, { recursive: true })
  return { copied: true }
}

/**
 * 现在是什么状态（只读，不写任何东西）。
 *
 * @param {{dataDir: string, root: string, connected?: boolean}} options
 */
function status({ dataDir, root, connected = false }) {
  const src = sourceDir(root)
  const manifest = readManifest(src)
  const extensionId = manifest ? idFromKey(manifest.key) : ''
  const target = targetDir(dataDir)
  const hostManifest = hostManifestPath(dataDir)

  let hostOk = false
  try {
    const json = JSON.parse(fs.readFileSync(hostManifest, 'utf8'))
    const origins = Array.isArray(json.allowed_origins) ? json.allowed_origins : []
    hostOk = Boolean(extensionId) && origins.includes(`chrome-extension://${extensionId}/`)
  } catch {
    hostOk = false
  }
  const regPath = readRegistryPath()

  return {
    extensionId,
    /** 产物有没有装到 data 下（Edge 要加载的就是这个目录） */
    staged: Boolean(readManifest(target)),
    /** 界面上要显示出来让人「加载解压缩的扩展」时去选它 */
    targetDir: target,
    hostManifest,
    wrapper: hostWrapperPath(dataDir),
    /** 宿主清单的 allowed_origins 已经是我们算出来的 ID */
    hostOk,
    /** 注册表指对了 */
    registered: Boolean(regPath) && path.resolve(regPath) === path.resolve(hostManifest),
    /** 扩展真的连上来了（桥上有活连接）—— 唯一能说「装好了」的判据 */
    connected: Boolean(connected),
    /** 产物源头在不在（打包漏了就是 false） */
    sourceOk: Boolean(manifest),
    sourceDir: src,
  }
}

/**
 * 真的装：拷产物 → 写 wrapper → 写宿主清单 → 写注册表。**幂等**。
 *
 * 幂等对用户很实在：点了两次、或者想「再装一遍」，不该造出第二份东西。
 *
 * @param {{dataDir: string, root: string}} options
 */
function apply({ dataDir, root }) {
  const src = sourceDir(root)
  const manifest = readManifest(src)
  const fail = (error) => ({ ok: false, error, ...status({ dataDir, root }) })
  if (!manifest) return fail(`扩展产物目录里没有 manifest.json：${src}`)

  const extensionId = idFromKey(manifest.key)
  if (!extensionId) return fail('扩展 manifest 缺少（或写坏了）key，算不出固定 ID')

  try {
    syncTarget(src, targetDir(dataDir))
  } catch (error) {
    return fail(`拷贝扩展产物失败：${error.message}`)
  }

  const runtime = hostRuntime(root)
  if (!fs.existsSync(runtime.exe) || !fs.existsSync(runtime.script)) {
    return fail(`找不到跑 native host 的可执行文件：${runtime.exe}`)
  }

  const wrapper = hostWrapperPath(dataDir)
  const hostManifest = hostManifestPath(dataDir)
  fs.mkdirSync(path.dirname(hostManifest), { recursive: true })
  fs.writeFileSync(wrapper, wrapperText({ dataDir, exe: runtime.exe, script: runtime.script }), 'ascii')

  const json = {
    name: HOST_NAME,
    description: 'Harbor browser companion host',
    path: wrapper,
    type: 'stdio',
    allowed_origins: [`chrome-extension://${extensionId}/`],
  }
  fs.writeFileSync(hostManifest, `${JSON.stringify(json, null, 2)}\n`, 'utf8')

  const reg = spawnSync(
    'reg',
    ['ADD', REG_KEY, '/ve', '/t', 'REG_SZ', '/d', hostManifest, '/f', '/reg:64'],
    { encoding: 'utf8', windowsHide: true },
  )
  if (reg.status !== 0) {
    return fail(`写注册表失败：${(reg.stderr || reg.stdout || '').trim() || 'reg ADD 返回非 0'}`)
  }
  /* 32 位视图：HKCU 下通常同一处，失败不算错（与仓库那份 install-host.cmd 同口径） */
  spawnSync('reg', ['ADD', REG_KEY, '/ve', '/t', 'REG_SZ', '/d', hostManifest, '/f', '/reg:32'], {
    windowsHide: true,
  })

  return { ok: true, ...status({ dataDir, root }) }
}

/** 打开 Edge 的扩展页（尽力而为；打不开由界面提示手动开） */
function openExtensionsPage() {
  const res = spawnSync('cmd', ['/c', 'start', '', 'msedge', 'edge://extensions'], {
    windowsHide: true,
  })
  return { ok: res.status === 0 }
}

module.exports = {
  HOST_NAME,
  REG_KEY,
  idFromKey,
  sourceDir,
  targetDir,
  hostManifestPath,
  hostWrapperPath,
  hostRuntime,
  wrapperText,
  readManifest,
  readRegistryPath,
  status,
  apply,
  openExtensionsPage,
}
